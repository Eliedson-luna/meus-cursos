# Diferença entre Lista e Tupla

# Lista 

minha_lista = ['Jurandr', 'Moises'] 

# Tupla 

minha_tupla = ('jurandir', 'Moises')

# A principal diferença da tupla para a 
# lista é o fato de seu tamanho não poder ser alterado, 
# contudo podermos alterar o conteudo de seus itens
# Usada principalmente quando já possui itens definidos

# Dicionarios 

meu_dicionario = { 'nome': 'Joao', 'idade': 48 }

# Semelhante ao formato JSON, construido no formato chave:valor

# Conjuto

meu_conjunto = {'moacir', 'alemao', 'dinho'}

# Semelhante à lista, porém não é ordenado, o que impossibilita o get de valores
# por indicies. Outra caracteristica é que não permite dados repetidos